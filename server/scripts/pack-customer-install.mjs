#!/usr/bin/env node
/**
 * Packs a pre-built Worker install ZIP for customer Cloudflare accounts.
 *
 * Flow:
 *   1. `wrangler deploy --dry-run` → dist/worker-build/index.js
 *   2. Stage worker.js + generated wrangler.toml + README + VERSION
 *   3. ZIP as relaybase-worker-install-{version}.zip
 *   4. Write worker-install-manifest.json (version, zipUrl, sha256)
 *   5. Copy to kembo/website/public/downloads/
 */
import {
  cpSync,
  mkdirSync,
  rmSync,
  existsSync,
  readFileSync,
  writeFileSync,
  createReadStream,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverRoot = join(__dirname, "..");
const repoRoot = join(serverRoot, "..");
const downloadsDir = join(repoRoot, "kembo", "website", "public", "downloads");
const DOWNLOAD_BASE = "https://relaybase.xyz/downloads";

const pkg = JSON.parse(readFileSync(join(serverRoot, "package.json"), "utf8"));
const version = pkg.version;
if (!version || version === "0.0.0") {
  console.error("Set a release version in server/package.json before packing.");
  process.exit(1);
}

const bundleDir = join(serverRoot, "dist", "worker-build");
const staging = join(serverRoot, "dist", "relaybase-worker-install");
const versionedZipName = `relaybase-worker-install-${version}.zip`;
const versionedZipPath = join(serverRoot, "dist", versionedZipName);
const stableZipPath = join(downloadsDir, "relaybase-worker-install.zip");
const versionedZipOut = join(downloadsDir, versionedZipName);
const manifestPath = join(downloadsDir, "worker-install-manifest.json");

console.log(`Building Worker bundle (v${version})…`);
execFileSync("npm", ["run", "build:bundle"], {
  cwd: serverRoot,
  stdio: "inherit",
});

const bundleCandidates = [
  join(bundleDir, "index.js"),
  join(bundleDir, "worker.js"),
];
const bundleSrc = bundleCandidates.find((p) => existsSync(p));
if (!bundleSrc) {
  console.error(
    `No bundled worker found under ${bundleDir}. Expected index.js or worker.js.`,
  );
  process.exit(1);
}

rmSync(staging, { recursive: true, force: true });
mkdirSync(staging, { recursive: true });

cpSync(bundleSrc, join(staging, "worker.js"));
writeFileSync(join(staging, "VERSION"), `${version}\n`);

const wranglerToml = `# Generated by pack-customer-install.mjs — do not edit by hand.
name = "relaybase-api"
main = "worker.js"
compatibility_date = "2025-06-01"

[vars]
WORKER_SCRIPT_NAME = "relaybase-api"
INBOUND_BUCKET_NAME = "relaybase-mailbox"
WORKER_VERSION = "${version}"

[triggers]
crons = ["*/15 * * * *"]

[[r2_buckets]]
binding = "INBOUND"
bucket_name = "relaybase-mailbox"

[[d1_databases]]
binding = "RELAYBASE_LOGS"
database_name = "relaybase-logs"
database_id = "REPLACE_WITH_relaybase-logs_ID"

[[d1_databases]]
binding = "RELAYBASE_INBOX_INDEX"
database_name = "relaybase-inbox-index"
database_id = "REPLACE_WITH_relaybase-inbox-index_ID"

[[d1_databases]]
binding = "RELAYBASE_DB"
database_name = "relaybase-db"
database_id = "REPLACE_WITH_relaybase-db_ID"
`;
writeFileSync(join(staging, "wrangler.toml"), wranglerToml);

cpSync(
  join(serverRoot, "customer-install", "README.md"),
  join(staging, "README.md"),
);
if (existsSync(join(serverRoot, "customer-install", ".dev.vars.example"))) {
  cpSync(
    join(serverRoot, "customer-install", ".dev.vars.example"),
    join(staging, ".dev.vars.example"),
  );
}

rmSync(versionedZipPath, { force: true });
execFileSync("zip", ["-r", versionedZipPath, "relaybase-worker-install"], {
  cwd: join(serverRoot, "dist"),
  stdio: "inherit",
});

const sha256 = await new Promise((resolve, reject) => {
  const hash = createHash("sha256");
  createReadStream(versionedZipPath)
    .on("data", (chunk) => hash.update(chunk))
    .on("end", () => resolve(hash.digest("hex")))
    .on("error", reject);
});

const manifest = {
  version,
  zipUrl: `${DOWNLOAD_BASE}/${versionedZipName}`,
  zipSha256: sha256,
  publishedAt: new Date().toISOString(),
};

mkdirSync(downloadsDir, { recursive: true });
cpSync(versionedZipPath, versionedZipOut);
cpSync(versionedZipPath, stableZipPath);
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

console.log(`Packed ${versionedZipPath}`);
console.log(`SHA-256: ${sha256}`);
console.log(`Copied ${versionedZipOut}`);
console.log(`Copied ${stableZipPath}`);
console.log(`Wrote ${manifestPath}`);
